import json
import shutil
from pathlib import Path

import pytest

from tools.generate_mscp_nist_800_171_mapping import (
    LINK_NOTE,
    MAPPING_FILE_NAME,
    REPORT_FILE_NAME,
    generate,
    main,
    report_path_for,
    requirement_number_for_citation,
)
from tools.json_output import write_json
from tools.mappings import validate_mappings

REPOSITORY_ROOT = Path(__file__).resolve().parent.parent
COMMITTED_BASELINES_DIR = REPOSITORY_ROOT / "baselines"
COMMITTED_REPORT_PATH = REPOSITORY_ROOT / "docs" / "mappings" / REPORT_FILE_NAME
MSCP_TAG = "release_9"
NIST_TAG = "v9.9.9"
REQUIREMENT_NUMBERS = ["03.01.01", "03.01.08", "03.13.08"]


def write_release(baselines_dir: Path, source_name: str, tag: str, rules: dict[str, dict]) -> dict:
    release_dir = baselines_dir / source_name / "releases" / tag
    (release_dir / "rules").mkdir(parents=True)
    entries = []
    for upstream_id, rule in rules.items():
        rule_file = f"rules/{upstream_id}.json"
        write_json(release_dir / rule_file, rule)
        entries.append({"id": f"{source_name}.{upstream_id}", "file": rule_file})
    write_json(release_dir / "_index.json", {"rules": entries})
    release = {"tag": tag, "index_path": f"{source_name}/releases/{tag}/_index.json"}
    return {"name": source_name, "release_tag": tag, "releases": [release]}


def mscp_rule(*citations: str) -> dict:
    return {"references": {"nist": {"800-171r3": list(citations), "800-53r5": ["AC-2"]}}}


def build_library(tmp_path: Path, mscp_rules: dict[str, dict] | None, include_nist: bool = True) -> Path:
    baselines_dir = tmp_path / "baselines"
    baselines_dir.mkdir()
    sources = []
    if mscp_rules is not None:
        sources.append(write_release(baselines_dir, "mscp", MSCP_TAG, mscp_rules))
    if include_nist:
        nist_rules = {number: {} for number in REQUIREMENT_NUMBERS}
        sources.append(write_release(baselines_dir, "nist_800_171", NIST_TAG, nist_rules))
    write_json(baselines_dir / "_manifest.json", {"schema_version": 7, "sources": sources})
    return baselines_dir


def read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


@pytest.mark.parametrize(
    ("citation", "expected"),
    [("03.01.08", "03.01.08"), ("3.1.8", None), ("03.01.08a", None), ("AC.L2-3.1.8", None), ("03.01", None)],
)
def test_requirement_number_for_citation(citation, expected):
    assert requirement_number_for_citation(citation) == expected


def test_rev_3_citations_link_to_requirements_and_others_are_reported(tmp_path):
    baselines_dir = build_library(
        tmp_path, {"rule": mscp_rule("03.01.08", "03.99.01", "3.1.1", "03.01.01", "03.01.08")}
    )
    report_path = report_path_for(baselines_dir)

    result = generate(baselines_dir, report_path)

    (link,) = read_json(baselines_dir / "_mappings" / "rules" / MAPPING_FILE_NAME)["links"]
    assert link == {
        "relation": "supports",
        "from": [{"kind": "rule", "id": "mscp.rule", "release": MSCP_TAG}],
        "to": [
            {"kind": "rule", "id": "nist_800_171.03.01.08", "release": NIST_TAG},
            {"kind": "rule", "id": "nist_800_171.03.01.01", "release": NIST_TAG},
        ],
        "note": LINK_NOTE,
    }
    assert read_json(report_path) == {
        "schema_version": 1,
        "mscp_release": MSCP_TAG,
        "nist_800_171_release": NIST_TAG,
        "unresolved": result.unresolved,
    }
    assert [(item["citation"], item["reason"]) for item in result.unresolved] == [
        ("03.01.08", "duplicate_citation"),
        ("03.99.01", "not_in_release"),
        ("3.1.1", "unrecognised_format"),
    ]


def test_link_note_and_header_wording(tmp_path):
    assert LINK_NOTE == (
        "Generated from mSCP's own references: mSCP lists this 800-171 requirement for this rule. "
        "Not reviewed by this project."
    )
    baselines_dir = build_library(tmp_path, {"rule": mscp_rule("03.01.01")})

    generate(baselines_dir, report_path_for(baselines_dir))

    mapping = read_json(baselines_dir / "_mappings" / "rules" / MAPPING_FILE_NAME)
    assert (mapping["id"], mapping["generated_by"]) == (
        "mscp-to-nist-800-171",
        "python tools/generate_mscp_nist_800_171_mapping.py",
    )
    assert mapping["description"] == (
        "mSCP rules linked to the NIST SP 800-171 requirements mSCP itself cites for them. "
        f"Generated by `python tools/generate_mscp_nist_800_171_mapping.py` from mSCP {MSCP_TAG} and "
        f"NIST SP 800-171 {NIST_TAG}; do not edit by hand."
    )


def test_nothing_is_written_without_the_800_171_source(tmp_path, capsys):
    baselines_dir = build_library(tmp_path, {"rule": mscp_rule("03.01.01")}, include_nist=False)

    assert main(["--baselines-dir", str(baselines_dir)]) == 1
    assert not (baselines_dir / "_mappings").exists()
    assert "needs both 'mscp' and 'nist_800_171'" in capsys.readouterr().err


def test_cli_summary_names_800_171(tmp_path, capsys):
    baselines_dir = build_library(tmp_path, {"rule": mscp_rule("03.01.01")})

    assert main(["--baselines-dir", str(baselines_dir)]) == 0
    assert capsys.readouterr().out == (
        f"Wrote 1 links (1 pairs) from mSCP {MSCP_TAG} to NIST SP 800-171 {NIST_TAG}; 0 citations unresolved\n"
    )


def test_committed_mapping_and_report_are_what_the_generator_produces(tmp_path):
    baselines_copy = tmp_path / "baselines"
    shutil.copytree(COMMITTED_BASELINES_DIR, baselines_copy)
    (baselines_copy / "_mappings" / "rules" / MAPPING_FILE_NAME).unlink()
    report_copy = tmp_path / "report.json"

    generate(baselines_copy, report_copy)

    committed_mapping = COMMITTED_BASELINES_DIR / "_mappings" / "rules" / MAPPING_FILE_NAME
    assert (baselines_copy / "_mappings" / "rules" / MAPPING_FILE_NAME).read_bytes() == committed_mapping.read_bytes()
    assert report_copy.read_bytes() == COMMITTED_REPORT_PATH.read_bytes()


def test_committed_mapping_has_the_expected_size_and_validates():
    mappings_dir = COMMITTED_BASELINES_DIR / "_mappings" / "rules"
    links = read_json(mappings_dir / MAPPING_FILE_NAME)["links"]
    assert len(links) == 233
    assert sum(len(link["to"]) for link in links) == 367
    # mSCP release_27.1 still cites 03.13.03, which Rev. 3 withdrew (addressed by 03.01.01 to 03.01.07).
    assert read_json(COMMITTED_REPORT_PATH)["unresolved"] == [
        {"citation": "03.13.03", "reason": "not_in_release", "rule": "mscp.system_settings_software_update_enforce"}
    ]

    errors, warnings = validate_mappings(mappings_dir, COMMITTED_BASELINES_DIR)

    assert errors == []
    assert [warning for warning in warnings if MAPPING_FILE_NAME in warning] == []
